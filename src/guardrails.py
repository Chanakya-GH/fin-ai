"""
Financial Safety Guardrails Module.

Implements Pre-Inference and Post-Inference safety gates for the
AI Financial Advisory Agent pipeline.

Pre-Inference (Stage 1): Blocks adversarial injections, illicit finance queries, and masks PII.
Post-Inference (Stage 3): Verifies numerical & lexical grounding against retrieved RAG chunks.
"""
import re
from dataclasses import dataclass


@dataclass
class GuardrailResult:
    """Result from a guardrail check."""
    passed: bool
    reason: str
    grounding_score: float = 1.0
    sanitized_text: str = ""


class FinancialSafetyGuardrails:
    """
    Implements Pre-Inference and Post-Inference safety gates.
    
    Stage 1 (Pre-Inference): Adversarial jailbreak detection, prompt injection
    blocking, illicit finance pattern matching, and PII masking.
    
    Stage 3 (Post-Inference): Numerical fact-checking and lexical overlap
    grounding verification against retrieved RAG source chunks.
    """
    
    # Stage 1: Adversarial Jailbreak, Prompt Injection & Illicit Finance Patterns
    ADVERSARIAL_PATTERNS = [
        r"ignore\s+(all\s+)?(previous|prior)\s+instructions",
        r"system\s+prompt",
        r"you\s+are\s+now\s+(dan|unrestricted|jailbroken)",
        r"bypass\s+(safety|compliance|sec|sebi|guardrails)",
        r"(insider\s+trading|pump\s+and\s+dump|money\s+laundering|tax\s+evasion)",
        r"guaranteed\s+(?:(?:100%|10x|double|\d+x|\d+%)\s+)?(return|profit|gain|tomorrow)",
        r"guaranteed\s+(100%|10x|double|return|profit)",
        r"pretend\s+you\s+are\s+a\s+licensed\s+fiduciary\s+giving\s+binding",
        r"\b10x\s+tomorrow\b",
    ]

    PII_PATTERNS = {
        "SSN": r"\b\d{3}-\d{2}-\d{4}\b",
        "CREDIT_CARD": r"\b(?:\d[ -]*?){13,16}\b",
        "PAN_INDIA": r"\b[A-Z]{5}[0-9]{4}[A-Z]{1}\b",
    }

    DISCLAIMER = (
        "\n\n*Disclaimer: This response is generated by an AI assistant for informational "
        "purposes only and does not constitute certified fiduciary, legal, or investment advice.*"
    )

    def pre_inference_check(self, user_query: str) -> GuardrailResult:
        """
        Stage 1: Pre-Inference Input Gate.
        
        Blocks adversarial injections, illicit queries, and masks PII
        before the query reaches the RAG + LLM pipeline.
        
        Args:
            user_query: Raw user input string.
            
        Returns:
            GuardrailResult with passed=False if blocked, or passed=True
            with sanitized_text containing PII-masked query.
        """
        lowered = user_query.lower()
        for pattern in self.ADVERSARIAL_PATTERNS:
            if re.search(pattern, lowered):
                return GuardrailResult(
                    passed=False,
                    reason="Blocked by Pre-Inference Guardrail: Adversarial or non-compliant intent detected.",
                )

        sanitized = user_query
        for pii_type, pattern in self.PII_PATTERNS.items():
            sanitized = re.sub(pattern, f"[REDACTED_{pii_type}]", sanitized)

        return GuardrailResult(passed=True, reason="OK", sanitized_text=sanitized)

    def post_inference_check(
        self, response: str, retrieved_chunks: list[dict], threshold: float = 0.65
    ) -> GuardrailResult:
        """
        Stage 3: Post-Inference Output Gate.
        
        Verifies numerical & lexical grounding against retrieved RAG chunks.
        Blocks responses that contain hallucinated numbers or insufficient
        overlap with source documents.
        
        Args:
            response: Raw LLM-generated response text.
            retrieved_chunks: List of dicts with 'text' key from RAG retrieval.
            threshold: Minimum grounding score to pass (default 0.65).
            
        Returns:
            GuardrailResult with grounding_score and either the response
            with disclaimer (if passed) or a safe fallback message (if blocked).
        """
        if not retrieved_chunks:
            return GuardrailResult(
                passed=False,
                grounding_score=0.0,
                reason="Blocked: No supporting source documents retrieved.",
            )

        combined_source = " ".join(c["text"].lower() for c in retrieved_chunks)

        # 1. Numerical Fact-Check: Any number/percentage in response must appear in context
        # Exclude citation markers like Source sec_001, [Source sec_12], etc. from being treated as financial claims
        cleaned_response = re.sub(r"\[?\(?\bSource\s+[a-zA-Z0-9_-]+\b\)?\]?", "", response, flags=re.IGNORECASE)
        norm_combined_source = combined_source.replace(",", "")
        response_numbers = re.findall(r"\b\d+(?:\.\d+)?%?\b", cleaned_response.replace(",", ""))
        ungrounded_numbers = [
            num for num in response_numbers if num not in norm_combined_source
        ]

        # 2. Content Token Grounding Overlap
        stop_words = {
            "the", "and", "for", "that", "this", "with", "from", "was",
            "are", "is", "in", "to", "of", "a", "an", "it", "its",
            "be", "been", "being", "have", "has", "had", "do", "does",
            "did", "will", "would", "could", "should", "may", "might",
            "shall", "can", "need", "dare", "ought", "used", "than",
            "very", "just", "about", "also", "more", "most", "some",
            "such", "only", "other", "into", "over", "after", "before",
            "between", "under", "above", "below", "each", "every",
        }
        resp_tokens = [
            w for w in re.findall(r"\b[a-zA-Z]{4,}\b", response.lower())
            if w not in stop_words
        ]
        if not resp_tokens:
            lexical_overlap = 1.0
        else:
            matched = sum(1 for w in resp_tokens if w in combined_source)
            lexical_overlap = matched / len(resp_tokens)

        num_penalty = 0.25 * len(ungrounded_numbers)
        grounding_score = max(0.0, min(1.0, lexical_overlap - num_penalty))

        if grounding_score < threshold:
            return GuardrailResult(
                passed=False,
                grounding_score=round(grounding_score, 3),
                reason="Blocked by Post-Inference Guardrail: Response failed source grounding verification.",
                sanitized_text=(
                    "I cannot verify this calculation or claim against the official SEC filings "
                    "in my knowledge base. Please consult the primary financial statements."
                ),
            )

        return GuardrailResult(
            passed=True,
            grounding_score=round(grounding_score, 3),
            reason="Verified",
            sanitized_text=response.strip() + self.DISCLAIMER,
        )
